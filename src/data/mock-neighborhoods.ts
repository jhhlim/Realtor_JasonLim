function trend(
  base: number,
  months = [
    "2025-08",
    "2025-09",
    "2025-10",
    "2025-11",
    "2025-12",
    "2026-01",
    "2026-02",
    "2026-03",
    "2026-04",
    "2026-05",
    "2026-06",
    "2026-07",
  ],
) {
  return months.map((month, i) => ({
    month,
    median: Math.round(base * (0.96 + i * 0.004)),
  }));
}

